import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeReport, updateIndex } from './analyze.mjs';

export const HISTORY_BRANCH = 'global-intelligence-history';
const ROOT = 'global-intelligence-network/data/';
export function gitClient({ token, repository, fetchImpl = fetch }) {
  if (!token) throw new Error('Missing GITHUB_TOKEN; no history published');
  if (!/^[\w.-]+\/[\w.-]+$/.test(repository ?? '')) throw new Error('Invalid GITHUB_REPOSITORY');
  const base = 'https://api.github.com/repos/' + repository;
  async function request(method, path, body, optional = false) {
    const response = await fetchImpl(base + path, {
      method,
      headers: { Accept: 'application/vnd.github+json',
        Authorization: 'Bearer ' + token,
        'X-GitHub-Api-Version': '2022-11-28',
        'Content-Type': 'application/json',
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      signal: AbortSignal.timeout(12000),
    });
    if (optional && response.status === 404) return null;
    if (!response.ok) throw new Error('GitHub API ' + response.status + ' on ' + method + ' ' + path);
    return response.json();
  }
  return {
    async branchHead(branch) {
      const ref = await request('GET', '/git/ref/heads/' + encodeURIComponent(branch), undefined, true);
      return ref?.object?.sha ?? null;
    },
    async ensureBranch(branch, mainSha) {
      const existing = await this.branchHead(branch);
      if (existing) return existing;
      if (!/^[a-f0-9]{40}$/i.test(mainSha ?? '')) throw new Error('Missing valid GITHUB_SHA for new history branch');
      await request('POST', '/git/refs', { ref: 'refs/heads/' + branch, sha: mainSha });
      return this.branchHead(branch);
    },
    async json(branch, path) {
      const item = await request('GET', '/contents/' + path + '?ref=' + encodeURIComponent(branch), undefined, true);
      if (!item) return null;
      if (item.encoding !== 'base64' || typeof item.content !== 'string') {
        throw new Error('Unexpected GitHub JSON content encoding');
      }
      return JSON.parse(Buffer.from(item.content.replace(/\s+/g, ''), 'base64').toString('utf8'));
    },
    async commit(branch, parent, files) {
      const existing = await request('GET', '/git/commits/' + parent);
      if (!existing?.tree?.sha) throw new Error('History parent tree not found');
      const tree = await request('POST', '/git/trees', {
        base_tree: existing.tree.sha, tree: files.map(file => ({
          path: file.path, mode: '100644', type: 'blob', content: JSON.stringify(file.value, null, 2) + '\n',
        })),
      });
      const commit = await request('POST', '/git/commits', {
        message: 'Record timestamped global intelligence collection',
        tree: tree.sha, parents: [parent],
      });
      await request('PATCH', '/git/refs/heads/' + encodeURIComponent(branch), {
        sha: commit.sha, force: false,
      });
      return commit.sha;
    },
  };
}

export async function publish(report, { env = process.env, fetchImpl = fetch,
  branch = HISTORY_BRANCH } = {}) {
  const client = gitClient({
    token: env.GITHUB_TOKEN, repository: env.GITHUB_REPOSITORY, fetchImpl,
  });
  const head = await client.ensureBranch(branch, env.GITHUB_SHA);
  if (!head) throw new Error('Cannot find history branch');
  const [previous, oldIndex] = await Promise.all([
    client.json(branch, ROOT + 'latest.json'),
    client.json(branch, ROOT + 'index.json'),
  ]);
  if (previous?.runId === report.runId) {
    return { status: 'already-published', branch, commit: head, runId: report.runId };
  }
  // Report generated by scan is safe to recompute against authoritative history.
  const latest = makeReport(report, previous);
  const index = updateIndex(oldIndex, latest);
  const files = [
    { path: ROOT + 'latest.json', value: latest },
    { path: ROOT + 'index.json', value: index },
    { path: ROOT + 'snapshots/' + latest.runId + '.json', value: latest },
  ];
  const commit = await client.commit(branch, head, files);
  return { status: 'published', branch, commit, runId: latest.runId,
    snapshotCount: index.entries.length, observations: latest.observations.length,
    newInSample: latest.comparisons.newInSample };
}

async function main() {
  const file = process.argv[2] ?? 'data/latest.json';
  const report = JSON.parse(await readFile(resolve(file), 'utf8'));
  const result = await publish(report);
  console.log(JSON.stringify(result, null, 2));
}
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main().catch(e => { console.error('Publication failed:', e.message); process.exitCode = 1; });
}
